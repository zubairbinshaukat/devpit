// Writes src/content/docs/whats-new.md from the GitHub releases of the repo.
//
//   npm run whats-new                      fetch the releases and rewrite the page
//   node scripts/gen-whats-new.mjs file    read releases from a saved JSON file (offline)
//
// It is run by hand after a release (see docs/releasing.md) and the result is
// committed, so a deploy never depends on the GitHub API being reachable and
// never hits its rate limit. Set GITHUB_TOKEN to raise the limit.
//
// Nothing is invented: each entry is the release's own notes. Notes that are
// only a list of commit hashes (the first release) are replaced with one
// honest sentence and a link, because a list of "fix" commits helps nobody.
import fs from 'node:fs';
import path from 'node:path';

import { REPO } from '../site.config.mjs';
import { CONTENT_DIR } from './lib/pages.mjs';

const OWNER_REPO = REPO.replace('https://github.com/', '');
const OUT = path.join(CONTENT_DIR, 'whats-new.md');

async function fetchReleases() {
  const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'devpit-docs' };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const res = await fetch(`https://api.github.com/repos/${OWNER_REPO}/releases?per_page=100`, { headers });
  if (!res.ok) throw new Error(`GitHub API answered ${res.status}`);
  return res.json();
}

const long = (iso) =>
  new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });

/** Cleans one release body into Markdown for the page, or '' if it has no real notes. */
export function cleanBody(body) {
  let text = (body ?? '').replace(/\r\n/g, '\n');
  // The release title repeats the tag.
  text = text.replace(/^##\s+Devpit v[\w.+-]+\s*\n/, '');
  // Drop the generated verification boilerplate.
  text = text.replace(/\n##\s+Verifying this release[\s\S]*$/, '');
  // Drop the "install or upgrade" block: the Getting started page owns it.
  text = text.replace(/\n###\s+Install or upgrade[\s\S]*$/, '');
  // A changelog that is only commit hashes is noise.
  const withoutCommits = text
    .split('\n')
    .filter((l) => !/^\*\s+[0-9a-f]{40}:/.test(l) && !/^##\s+Changelog\s*$/.test(l) && !/^###\s+Other\s*$/.test(l))
    .join('\n')
    .trim();
  if (!withoutCommits) return '';
  // Under "## vX" our sections are ### already. Make sure none is shallower.
  return withoutCommits.replace(/^##(?!#)\s/gm, '### ').replace(/\n{3,}/g, '\n\n');
}

export function render(releases) {
  const stable = releases.filter((r) => !r.draft).sort((a, b) => new Date(b.published_at) - new Date(a.published_at));
  const out = [
    '---',
    "title: What's new in Devpit",
    'description: What changed in each Devpit release, from new screens to fixes, taken straight from the GitHub release notes.',
    'sidebar:',
    "  label: What's new",
    'related:',
    '  - getting-started',
    '  - command-line',
    '---',
    '',
    '<!-- GENERATED by scripts/gen-whats-new.mjs from the GitHub releases. Do not edit by hand. -->',
    '',
    `Every release is listed here, newest first. The same notes are on the [GitHub releases page](${REPO}/releases).`,
    '',
    'To upgrade, see [Getting started](/docs/getting-started#update-devpit).',
    '',
  ];
  for (const r of stable) {
    const version = r.tag_name;
    out.push(`## ${version}`, '');
    out.push(`Released ${long(r.published_at)}${r.prerelease ? ' (pre-release)' : ''}. [Release page](${r.html_url})`, '');
    const body = cleanBody(r.body);
    out.push(
      body ||
        'This release has no written notes. See the [release page](' +
          r.html_url +
          ') for the files and checksums.',
      '',
    );
  }
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const file = process.argv[2];
  const releases = file ? JSON.parse(fs.readFileSync(file, 'utf8')) : await fetchReleases();
  fs.writeFileSync(OUT, render(releases));
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${releases.length} releases)`);
}
